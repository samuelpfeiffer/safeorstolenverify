/**
 * Writes public/sitemap.xml from the ACTUAL route table.
 *
 * Runs via the predev/prebuild npm hooks. Never edit public/sitemap.xml by
 * hand — add the route to the router and it appears here automatically.
 * Private routes (see scripts/route-manifest.mjs) are excluded.
 *
 * Existing <lastmod>/<changefreq>/<priority> values are preserved per URL;
 * lastmod is never invented from the build date.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { publicRoutes } from './route-manifest.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'public/sitemap.xml');
const BASE_URL = 'https://safeorstolen.com';

function existingMeta() {
  const map = new Map();
  if (!fs.existsSync(OUT)) return map;
  const xml = fs.readFileSync(OUT, 'utf-8');
  for (const m of xml.matchAll(/<url>([\s\S]*?)<\/url>/g)) {
    const block = m[1];
    const loc = (block.match(/<loc>([^<]+)<\/loc>/) || [])[1];
    if (!loc) continue;
    const p = loc.trim().replace(BASE_URL, '') || '/';
    map.set(p.length > 1 ? p.replace(/\/$/, '') : '/', {
      lastmod: (block.match(/<lastmod>([^<]+)<\/lastmod>/) || [])[1],
      changefreq: (block.match(/<changefreq>([^<]+)<\/changefreq>/) || [])[1],
      priority: (block.match(/<priority>([^<]+)<\/priority>/) || [])[1],
    });
  }
  return map;
}

function defaultsFor(p) {
  if (p === '/') return { changefreq: 'weekly', priority: '1.0' };
  if (p.startsWith('/blog')) return { changefreq: 'weekly', priority: '0.6' };
  return { changefreq: 'monthly', priority: '0.7' };
}

const prev = existingMeta();
const routes = publicRoutes();

const urls = routes.map((p) => {
  const meta = { ...defaultsFor(p), ...(prev.get(p) || {}) };
  const loc = `${BASE_URL}${p === '/' ? '/' : p}`;
  return [
    '  <url>',
    `    <loc>${loc}</loc>`,
    meta.lastmod ? `    <lastmod>${meta.lastmod}</lastmod>` : null,
    meta.changefreq ? `    <changefreq>${meta.changefreq}</changefreq>` : null,
    meta.priority ? `    <priority>${meta.priority}</priority>` : null,
    '  </url>',
  ]
    .filter(Boolean)
    .join('\n');
});

const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- GENERATED by scripts/generate-sitemap.mjs from src/core/routing/AppRoutes.tsx — do not edit by hand -->',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...urls,
  '</urlset>',
  '',
].join('\n');

fs.writeFileSync(OUT, xml);
console.log(`sitemap.xml written (${routes.length} public URLs)`);
