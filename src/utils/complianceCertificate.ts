import jsPDF from 'jspdf';

interface VerificationData {
  score: number;
  status: string;
  sources: string[];
  serial: string;
  itemType: string;
  timestamp: string;
  hash: string;
  tldr: string;
}

export const generateCompliancePDF = (data: VerificationData) => {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header
  doc.setFillColor(15, 18, 25);
  doc.rect(0, 0, pageWidth, 50, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(22);
  doc.setFont('helvetica', 'bold');
  doc.text('SafeOrStolen', 20, 25);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'normal');
  doc.text('Compliance Verification Certificate', 20, 38);

  // Certificate ID / Hash
  doc.setFontSize(8);
  doc.setTextColor(180, 180, 180);
  doc.text(`Certificate ID: ${data.hash}`, pageWidth - 20, 25, { align: 'right' });
  doc.text(`Generated: ${new Date(data.timestamp).toLocaleString()}`, pageWidth - 20, 33, { align: 'right' });

  // Status badge
  const y = 65;
  const statusColor = data.status === 'clean' ? [52, 211, 153] :
                       data.status === 'flagged' ? [251, 191, 36] : [248, 113, 113];

  doc.setFillColor(statusColor[0], statusColor[1], statusColor[2]);
  doc.roundedRect(20, y - 8, 50, 14, 3, 3, 'F');
  doc.setTextColor(0, 0, 0);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text(data.status.toUpperCase(), 45, y, { align: 'center' });

  doc.setFontSize(24);
  doc.setTextColor(statusColor[0], statusColor[1], statusColor[2]);
  doc.text(`Trust Score: ${data.score}/100`, 80, y + 2);

  // Divider
  doc.setDrawColor(50, 50, 60);
  doc.line(20, y + 15, pageWidth - 20, y + 15);

  // Details
  doc.setTextColor(60, 60, 70);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');

  let detailY = y + 30;
  const details = [
    ['Identifier', data.serial],
    ['Item Type', data.itemType],
    ['Verification Status', data.status.toUpperCase()],
    ['Trust Score', `${data.score}/100`],
    ['Timestamp', new Date(data.timestamp).toLocaleString()],
    ['Certificate Hash', data.hash],
    ['Sources Checked', data.sources.length.toString()],
  ];

  details.forEach(([label, value]) => {
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(80, 80, 90);
    doc.text(label + ':', 20, detailY);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(30, 30, 40);
    doc.text(value, 80, detailY);
    detailY += 10;
  });

  // Sources
  detailY += 5;
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(80, 80, 90);
  doc.text('Databases Checked:', 20, detailY);
  detailY += 8;
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(30, 30, 40);
  data.sources.forEach(source => {
    doc.text(`• ${source}`, 25, detailY);
    detailY += 7;
  });

  // TL;DR
  detailY += 10;
  doc.setFillColor(245, 245, 250);
  doc.roundedRect(20, detailY - 5, pageWidth - 40, 25, 3, 3, 'F');
  doc.setFontSize(9);
  doc.setFont('helvetica', 'italic');
  doc.setTextColor(60, 60, 70);
  doc.text(data.tldr, 25, detailY + 5, { maxWidth: pageWidth - 50 });

  // Footer
  const footerY = doc.internal.pageSize.getHeight() - 30;
  doc.setDrawColor(50, 50, 60);
  doc.line(20, footerY, pageWidth - 20, footerY);

  doc.setFontSize(7);
  doc.setTextColor(150, 150, 160);
  doc.text('This certificate is generated by SafeOrStolen LLC for due diligence purposes.', 20, footerY + 8);
  doc.text('It is not a legal guarantee. Always contact local law enforcement for definitive verification.', 20, footerY + 14);
  doc.text(`Cryptographic Hash: ${data.hash} | safeorstolen.com`, pageWidth - 20, footerY + 8, { align: 'right' });

  // Download
  doc.save(`SafeOrStolen-Certificate-${data.hash.slice(0, 8)}.pdf`);
};
