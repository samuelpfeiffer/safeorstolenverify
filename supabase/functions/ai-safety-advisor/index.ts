import "https://deno.land/x/xhr@0.1.0/mod.ts";
import { serve } from "https://deno.land/std@0.168.0/http/server.ts";
import { createClient } from 'https://esm.sh/@supabase/supabase-js@2.39.3';

const openAIApiKey = Deno.env.get('OPENAI_API_KEY');

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
};

serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages, context } = await req.json();

    const supabase = createClient(
      Deno.env.get('SUPABASE_URL') ?? '',
      Deno.env.get('SUPABASE_ANON_KEY') ?? '',
      { global: { headers: { Authorization: req.headers.get('Authorization')! } } }
    );

    const systemPrompt = `You are SafeOrStolen's AI Safety Advisor. Your role is to help users make safe purchasing decisions and avoid stolen goods.

Context about the platform:
- SafeOrStolen verifies serial numbers, IMEIs, and VINs against stolen item databases
- We check multiple sources: NICB, IMEI.info, CheckMEND, Bike Index, and more
- Users can search before buying to protect themselves from stolen goods

Your responsibilities:
1. Help users understand verification results
2. Explain what red flags to look for when buying used items
3. Provide safety tips for different item types (phones, bikes, vehicles, electronics)
4. Explain legal implications of buying stolen goods
5. Guide users on what to do if they find a suspicious item
6. Answer questions about the verification process

${context ? `Current context: ${JSON.stringify(context)}` : ''}

Be concise, helpful, and focus on practical safety advice. If discussing legal matters, remind users to consult local authorities.`;

    console.log('AI Safety Advisor request with', messages.length, 'messages');

    const response = await fetch('https://api.openai.com/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${openAIApiKey}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: 'gpt-4o-mini',
        messages: [
          { role: 'system', content: systemPrompt },
          ...messages
        ],
        temperature: 0.7,
        max_tokens: 500,
      }),
    });

    if (!response.ok) {
      const errorData = await response.text();
      console.error('OpenAI API error:', errorData);
      throw new Error(`OpenAI API error: ${response.status}`);
    }

    const data = await response.json();
    const assistantMessage = data.choices[0].message.content;

    console.log('AI response generated successfully');

    return new Response(JSON.stringify({ 
      message: assistantMessage,
      usage: data.usage 
    }), {
      headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  } catch (error) {
    console.error('Error in ai-safety-advisor:', error);
    return new Response(JSON.stringify({ error: error.message }), {
      status: 500,
      headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    });
  }
});
